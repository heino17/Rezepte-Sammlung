/* BCP-47-Tag für Intl-/html-Attribute: "zh_CN" -> "zh-CN". Für die
 * Wörterbuch-Suche bleibt "sprache" unverändert ("zh_CN"). */
function sprachTag() {
  return sprache.replace("_", "-");
}

/* Liefert den übersetzten Text; bei fehlender Übersetzung den deutschen
 * Ausgangstext. {name}-Platzhalter werden ersetzt. */
function tr(text, vars) {
  var ausgabe = text;
  var dict = sprachen[sprache];
  if (dict && dict[text] != null) ausgabe = dict[text];
  if (vars) {
    for (var k in vars) ausgabe = ausgabe.split("{" + k + "}").join(vars[k]);
  }
  return ausgabe;
}

/* Pluralkategorie der aktuellen Sprache für n. Deutsch/Englisch kennen nur
 * Einzahl (1) und Mehrzahl; Russisch unterscheidet zusätzlich "few" (2-4). */
function pluralKategorie(n) {
  if (sprache === "ru") {
    n = Math.abs(Math.floor(n));
    if (n % 10 === 1 && n % 100 !== 11) return "one";
    if (n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 10 || n % 100 >= 20)) return "few";
    return "many";
  }
  return n === 1 ? "one" : "many";
}

/* Plural: bei "one" die Einzahl-, sonst die Mehrzahl-Variante. Für Sprachen
 * mit drei Formen (Russisch) liefert das Wörterbuch unter PLURAL_FEW die
 * "wenige"-Form, nachgeschlagen über den Mehrzahl-Schlüssel. */
function trPlural(anzahl, eins, mehrere) {
  var kat = pluralKategorie(anzahl);
  if (kat === "one") return tr(eins, { anzahl: anzahl });
  var d = sprachen[sprache];
  if (kat === "few" && d && d.PLURAL_FEW && d.PLURAL_FEW[mehrere] != null) {
    return d.PLURAL_FEW[mehrere].split("{anzahl}").join(anzahl);
  }
  return tr(mehrere, { anzahl: anzahl });
}

