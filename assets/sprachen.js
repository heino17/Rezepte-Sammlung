/* Anzeige -> gespeicherter deutscher Wert (Rückübersetzung).
 * Mehrere deutsche Einheiten teilen sich je Sprache dieselbe Anzeige
 * (z. B. "St."/"Stk." -> "pcs.", ja/ko/zh_CN "Tasse"/"Becher" -> "杯"),
 * ein reiner Rückscan ist daher zwangsläufig verlustbehaftet.
 * Der optionale Parameter `original` bewahrt die Identität: Entspricht `u`
 * exakt der Anzeige des bisherigen Werts, wurde der Text nur übersetzt und
 * nicht geändert – dann kehrt das Original unverändert zurück. So bleiben
 * Roundtrips über Anzeige-Felder verlustfrei; nur echte Neueingaben werden
 * kanonisiert (Ersttreffer gewinnt). */
function einheitKanonisch(u, original) {
  var m = EINHEITEN_ANZEIGE[sprache];
  if (!m || u == null) return u;
  if (original != null && original !== "" && u === einheitAnzeige(original)) return original;
  for (var k in m) {
    if (m[k] === u) return k;
  }
  return u;
}

/* Übersetzt statische Texte im DOM: [data-i18n] (Text), [data-i18n-ph]
 * (placeholder), [data-i18n-title] (title), <title> über data-i18n.
 * Nach innerHTML-Wechseln auf dem Container erneut aufrufen. */
function uebersetzeDOM(root) {
  var basis = root || document;
  var liste = basis.querySelectorAll("[data-i18n]");
  for (var i = 0; i < liste.length; i++) {
    var el = liste[i];
    var key = el.getAttribute("data-i18n");
    if (el.tagName === "TITLE") { document.title = tr(key); continue; }
    el.textContent = tr(key);
  }
  liste = basis.querySelectorAll("[data-i18n-ph]");
  for (var j = 0; j < liste.length; j++) {
    liste[j].placeholder = tr(liste[j].getAttribute("data-i18n-ph"));
  }
  liste = basis.querySelectorAll("[data-i18n-title]");
  for (var k = 0; k < liste.length; k++) {
    liste[k].title = tr(liste[k].getAttribute("data-i18n-title"));
  }
  liste = basis.querySelectorAll("[data-i18n-aria]");
  for (var m = 0; m < liste.length; m++) {
    liste[m].setAttribute("aria-label", tr(liste[m].getAttribute("data-i18n-aria")));
  }
  liste = basis.querySelectorAll("[data-i18n-value]");
  for (var n = 0; n < liste.length; n++) {
    liste[n].value = tr(liste[n].getAttribute("data-i18n-value"));
  }
}

