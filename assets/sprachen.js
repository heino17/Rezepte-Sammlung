/* Aus der Browsersprache ("en-US", "zh-CN", "de_AT" …) einen unterstützten
 * Sprachcode ableiten – oder null, wenn keine Sprache passt. */
function browserSprache() {
  var b = (navigator.language || navigator.userLanguage || "").toLowerCase().replace("_", "-");
  if (!b) return null;
  if (b.indexOf("zh") === 0) return "zh_CN"; /* zh, zh-CN, zh-TW … -> eine chinesische Fassung */
  var basis = b.split("-")[0];
  return SPRACH_CODES.indexOf(basis) !== -1 ? basis : null;
}

/* Priorität: ?lang=xx > gespeicherte Wahl > STANDARD_SPRACHE;
 * bei STANDARD_SPRACHE="auto" dazwischen die Browsersprache, sonst als
 * letzte Rückfallebene "de". */
function aktuelleSprache() {
  var url = new URLSearchParams(location.search).get("lang");
  if (SPRACH_CODES.indexOf(url) !== -1) return url;
  try {
    var g = localStorage.getItem(SPRACH_KEY);
    if (SPRACH_CODES.indexOf(g) !== -1) return g;
  } catch (e) { /* ignorieren */ }
  if (STANDARD_SPRACHE === "auto") {
    var bs = browserSprache();
    if (bs != null) return bs;
  }
  if (SPRACH_CODES.indexOf(STANDARD_SPRACHE) !== -1) return STANDARD_SPRACHE;
  return "de";
}

